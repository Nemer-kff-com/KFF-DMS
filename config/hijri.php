/** @return list<int> */
function dms_ummalqura_mjdn_table(): array
{
    static $table = null;
    if ($table !== null) {
        return $table;
    }
    $sum = 28607;
    $table = [$sum];
    foreach (dms_ummalqura_month_lengths() as $days) {
        $sum += $days;
        $table[] = $sum;
    }
    return $table;
}

function dms_ummalqura_div(int $a, int $b): int
{
    return intdiv($a, $b);
}

function dms_ummalqura_g2d(int $gy, int $gm, int $gd): int
{
    $d = dms_ummalqura_div(($gy + dms_ummalqura_div($gm - 8, 6) + 100100) * 1461, 4)
        + dms_ummalqura_div(153 * (($gm + 9) % 12) + 2, 5)
        + $gd - 34840408;
    $d = $d - dms_ummalqura_div(dms_ummalqura_div($gy + 100100 + dms_ummalqura_div($gm - 8, 6), 100) * 3, 4) + 752;
    return $d;
}

/** @return array{0:int,1:int,2:int}|null */
function dms_ummalqura_from_gregorian(int $gy, int $gm, int $gd): ?array
{
    $table = dms_ummalqura_mjdn_table();
    $mjdn = dms_ummalqura_g2d($gy, $gm, $gd) - 2400000;
    $i = null;
    foreach ($table as $idx => $value) {
        if ($value > $mjdn) {
            $i = $idx;
            break;
        }
    }
    if ($i === null || $i < 1) {
        return null;
    }
    $totalMonths = $i + 16260;
    $cYears = intdiv($totalMonths - 1, 12);
    $hy = $cYears + 1;
    $hm = $totalMonths - 12 * $cYears;
    $hd = $mjdn - $table[$i - 1] + 1;
    if ($hy < 1356 || $hy > 1500 || $hm < 1 || $hm > 12 || $hd < 1 || $hd > 30) {
        return null;
    }
    return [$hy, $hm, $hd];
}

function dms_ummalqura_mod(int $a, int $b): int
{
    return $a - intdiv($a, $b) * $b;
}

function dms_ummalqura_h2d(int $hy, int $hm, int $hd): ?int
{
    $table = dms_ummalqura_mjdn_table();
    $totalMonths = (($hy - 1) * 12) + $hm;
    $i = $totalMonths - 16260;
    if ($i < 1 || $i >= count($table)) {
        return null;
    }
    return $hd + $table[$i - 1] - 1 + 2400000;
}

/** @return array{0:int,1:int,2:int} */
function dms_ummalqura_d2g(int $jdn): array
{
    $j = 4 * $jdn + 139361631;
    $j = $j + intdiv(intdiv(4 * $jdn + 183187720, 146097) * 3, 4) * 4 - 3908;
    $i = intdiv(dms_ummalqura_mod($j, 1461), 4) * 5 + 308;
    $gd = intdiv(dms_ummalqura_mod($i, 153), 5) + 1;
    $gm = dms_ummalqura_mod(intdiv($i, 153), 12) + 1;
    $gy = intdiv($j, 1461) - 100100 + intdiv(8 - $gm, 6);
    return [$gy, $gm, $gd];
}

/** @return array{0:int,1:int,2:int}|null */
function dms_ummalqura_to_gregorian(int $hy, int $hm, int $hd): ?array
{
    if ($hy < 1356 || $hy > 1500 || $hm < 1 || $hm > 12 || $hd < 1 || $hd > 30) {
        return null;
    }
    $jdn = dms_ummalqura_h2d($hy, $hm, $hd);
    if ($jdn === null) {
        return null;
    }
    return dms_ummalqura_d2g($jdn);
}
